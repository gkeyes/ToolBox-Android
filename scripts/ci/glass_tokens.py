"""Export the Compose theme defaults used by each standalone first-party tool."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THEME = ROOT / "core-ui/src/main/java/io/toolbox/core/ui/theme/ToolBoxTheme.kt"
SHEETS = {
    "nextflux": "src/design/tokens.css",
    "health-records": "web/style.css",
    "socialcoach": "src/app/globals.css",
}
BEGIN = "/* ToolBox theme defaults (generated by scripts/ci/glass_tokens.py). */"
END = "/* End ToolBox theme defaults. */"
BLOCK = re.compile(r"\n*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*", re.S)


def properties(kotlin):
    metrics = {}
    for group, names in {
        "ToolBoxRadii": ["card", "control", "sheet", "button", "badge", "denseSurface"],
        "ToolBoxSpacing": ["sm", "md", "lg"],
        "ToolBoxSizes": ["touchTarget"],
    }.items():
        section = kotlin.split("data class " + group + "(", 1)[1].split("\n)", 1)[0]
        for key in names:
            value = re.search(rf"val {key}: Dp = (\d+)\.dp", section)[1]
            metrics[key] = value + "px"
    sizes = kotlin.split("private val DefaultTextStyles =", 1)[1].split("\n)", 1)[0]
    for name in ("body", "sectionTitle", "headline"):
        sp = int(re.search(rf"\b{name} = TextStyle\(fontSize = (\d+)\.sp", sizes)[1])
        metrics[name] = f"{sp / 16:g}rem"
    recipes = kotlin.split("internal fun liquidGlassMaterials(", 1)[1]
    metrics["blur"] = re.search(r"blurRadius = (\d+)\.dp", recipes)[1] + "px"
    palettes = []
    for mode in ("Light", "Dark"):
        section = kotlin.split(mode + "ToolBoxColors = ToolBoxColorScheme(", 1)[1].split("\n)", 1)[0]
        colors = {}
        for key in ("primary", "background", "surface", "textPrimary"):
            match = re.search(rf"\b{key} = Color(?:\(0xFF([A-F0-9]{{6}})\)|\.(Black|White))", section)
            colors[key] = "#" + (match[1] or {"Black": "000000", "White": "FFFFFF"}[match[2]])
        # These are the host's legible overlay material and its opaque fallback.
        tone = "FFFFFF" if mode == "Light" else re.search(r"DarkOverlayGlass = Color\(0xFF([0-9A-F]{6})\)", kotlin)[1]
        rgb = " ".join(str(int(tone[i:i+2], 16)) for i in (0, 2, 4))
        alpha = re.search(r"overlayFill = overlay\(if \(dark\) ([.\d]+)f else ([.\d]+)f", recipes)
        rim = re.search(r"overlayBorder = if \(dark\) Color.White.copy\(alpha = ([.\d]+)f\) else Color.White.copy\(alpha = ([.\d]+)f", recipes)
        band = 2 if mode == "Light" else 1
        colors["overlay"] = f"rgb({rgb} / {alpha[band]})"
        colors["opaque"] = "#" + tone
        colors["rim"] = f"rgb(255 255 255 / {rim[band]})"
        palettes.append(colors)
    return metrics, palettes


def render(source, metrics, palettes):
    source = BLOCK.sub("", source).rstrip()
    used = set(re.findall(r"var\(--tbx-([\w]+)\)", source))
    unknown = used - metrics.keys() - palettes[0].keys()
    if unknown or not used:
        raise ValueError(f"Missing or unknown theme bindings: {unknown or used}")

    def lines(values, indent):
        return "\n".join(f"{indent}--tbx-{key}: {value};" for key, value in values.items() if key in used)

    root = lines({**metrics, **palettes[0]}, "  ")
    dark = lines(palettes[1], "    ")
    block = f"{BEGIN}\n:root {{\n{root}\n}}"
    if dark:
        block += f"\n@media (prefers-color-scheme: dark) {{\n  :root {{\n{dark}\n  }}\n}}"
        if '[data-theme="light"]' in source or '[data-theme="dark"]' in source:
            for name, palette in zip(("light", "dark"), palettes):
                block += f'\n:root[data-theme="{name}"] {{\n{lines(palette, "  ")}\n}}'
    return source + "\n\n" + block + "\n" + END + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    metrics, palettes = properties(THEME.read_text())
    changed = []
    for name in json.loads((ROOT / "scripts/ci/tbx-targets.json").read_text()):
        path = ROOT / "examples" / name / SHEETS.get(name, "style.css")
        source = path.read_text()
        result = render(source, metrics, palettes)
        if source != result:
            changed.append(name)
            if not args.check:
                path.write_text(result)
    if args.check and changed:
        raise SystemExit("Stale theme defaults: " + ", ".join(changed))


if __name__ == "__main__":
    main()
